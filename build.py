def fail(msg):
    sys.exit("エラー: " + msg)


def load_posts():
    posts = []
    for f in sorted(SRC.glob("*.html")):
        if f.name.startswith("_"):
            continue
        text = f.read_text(encoding="utf-8")
        m = re.match(r"\A---[ \t]*\n(.*?)\n---[ \t]*\n(.*)\Z", text, re.S)
        if not m:
            fail(f"{f.name}: 先頭に --- で囲んだ設定ブロックがありません")
        meta = {}
        for line in m.group(1).splitlines():
            if not line.strip() or line.strip().startswith("#"):
                continue
            key, _, val = line.partition(":")
            meta[key.strip()] = val.strip()
        body = m.group(2).strip()

        if meta.get("draft", "").lower() in ("true", "yes", "1"):
            continue

        for key in ("title", "date", "category", "description"):
            if not meta.get(key):
                fail(f"{f.name}: 設定ブロックに {key} がありません")
        if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", meta["date"]):
            fail(f"{f.name}: date は 2026-09-14 の形式で書いてください")
        if meta["category"] not in CATS:
            fail(f"{f.name}: category は {' / '.join(CATS)} のどれかにしてください")

        slug = meta.get("slug") or re.sub(r"^\d{4}-\d{2}-\d{2}-", "", f.stem)
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", slug):
            fail(f"{f.name}: slug は半角の小文字・数字・ハイフンだけで書いてください（現在: {slug}）")

        for ph in PLACEHOLDERS:
            if ph in meta["title"] or ph in body or ph in meta["date"]:
                fail(f"{f.name}: 書きかけの文言「{ph}」が残っています")

        try:
            order = int(meta.get("order", "0"))
        except ValueError:
            fail(f"{f.name}: order は数字で書いてください")

        posts.append({
            "file": f.name,
            "title": meta["title"],
            "date": meta["date"],
            "category": meta["category"],
            "slug": slug,
            "description": meta["description"],
            "order": order,
            "body": body,
        })

    seen = {}
    for p in posts:
        if p["slug"] in seen:
            fail(f"slug「{p['slug']}」が {seen[p['slug']]} と {p['file']} で重複しています")
        seen[p["slug"]] = p["file"]

    posts.sort(key=lambda p: (p["date"], p["order"]), reverse=True)
    return posts


def date_ja(iso):
    return iso.replace("-", ".")


def esc(s):
    return html.escape(s, quote=True)


