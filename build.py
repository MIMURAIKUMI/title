# ---------------------------------------------------------------- トップページ・サイトマップ
def update_index(posts):
    text = INDEX.read_text(encoding="utf-8")
    pattern = re.compile(r"<!-- DIARY-LIST:START -->.*?<!-- DIARY-LIST:END -->", re.S)
    if not pattern.search(text):
        fail("index.html に DIARY-LIST:START / END のマーカーがありません")
    block = (
        "<!-- DIARY-LIST:START -->\n"
        "    <!-- ここは build.py が自動生成します。直接編集しないでください -->\n"
        '    <div class="blog-list">\n'
        f"{post_items(posts)}\n"
        "    </div>\n"
        '    <p class="works-more"><a href="/diary/" data-en="See all posts »">すべての記事を見る »</a></p>\n'
        "    <!-- DIARY-LIST:END -->"
    )
    INDEX.write_text(pattern.sub(lambda _m: block, text, count=1), encoding="utf-8")


def write_sitemap(posts):
    urls = []
    for path in STATIC_URLS:
        urls.append((SITE + path, None))
    urls.append((SITE + "/diary/", posts[0]["date"] if posts else None))
    for p in posts:
        urls.append((f"{SITE}/diary/{p['slug']}/", p["date"]))
    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for loc, lastmod in urls:
        lines.append("  <url>")
        lines.append(f"    <loc>{loc}</loc>")
        if lastmod:
            lines.append(f"    <lastmod>{lastmod}</lastmod>")
        lines.append("  </url>")
    lines.append("</urlset>")
    (ROOT / "sitemap.xml").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    posts = load_posts()
    if not posts:
        fail("公開できる記事が diary-src/ にありません")

    OUT.mkdir(exist_ok=True)
    for i, p in enumerate(posts):
        newer = posts[i - 1] if i > 0 else None
        older = posts[i + 1] if i + 1 < len(posts) else None
        d = OUT / p["slug"]
        d.mkdir(parents=True, exist_ok=True)
        (d / "index.html").write_text(render_post(p, newer, older), encoding="utf-8")

    (OUT / "index.html").write_text(render_hub(posts), encoding="utf-8")

    # 削除した（または draft にした）記事のページを片付ける。build.py が作ったものだけ消す。
    slugs = {p["slug"] for p in posts}
    for d in OUT.iterdir():
        page = d / "index.html"
        if d.is_dir() and d.name not in slugs and page.exists() and MARK in page.read_text(encoding="utf-8"):
            shutil.rmtree(d)
            print(f"  削除: diary/{d.name}/")

    update_index(posts)
    write_sitemap(posts)

    print(f"完了: {len(posts)} 件の記事を生成しました")
    for p in posts:
        print(f"  {p['date']}  /diary/{p['slug']}/  {p['title'][:36]}")


if __name__ == "__main__":
    main()
